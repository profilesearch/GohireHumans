"""Contracts for /llms-full.txt: the long-form reference AI assistants and agents read.

It is generated by scripts/build_llms_full.py from the visible FAQ cards and the MCP tool
definitions, so these tests pin that the published file matches its sources exactly.
"""
import ast
import re
import sys
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib import robotparser
from urllib.parse import urlsplit

BACKEND = Path(__file__).resolve().parent
ROOT = BACKEND.parent
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(BACKEND))

import build_llms_full  # noqa: E402
from test_ai_answer_readiness import FAQ_PAGES, AnswerHTML, claim_problems  # noqa: E402

FRONTEND = ROOT / "frontend"
SITE = "https://www.gohirehumans.com/"
PACKAGE_SOURCE = "git+https://github.com/profilesearch/GohireHumans#subdirectory=backend/mcp-package"


def full_text():
    return (FRONTEND / "llms-full.txt").read_text(encoding="utf-8")


def literal(path, name):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise AssertionError(f"{name} not found in {path}")


class LlmsFullTests(unittest.TestCase):
    def test_published_file_is_the_generated_output(self):
        self.assertEqual(full_text(), build_llms_full.render(), "run: python3 scripts/build_llms_full.py")

    def test_every_visible_faq_answer_appears_verbatim(self):
        text = full_text()
        count = 0
        for relative in FAQ_PAGES:
            for question, answer in AnswerHTML((FRONTEND / relative).read_text(encoding="utf-8")).pairs:
                count += 1
                with self.subTest(question=question):
                    self.assertIn(f"### {question}\n\n{answer}\n\nSource: {SITE}{relative}", text)
        self.assertEqual(count, sum(len(q) for q in FAQ_PAGES.values()))

    def test_lists_exactly_the_mcp_tools_and_resources_the_server_ships(self):
        text = full_text()
        section = lambda title: text.split(f"### {title}\n", 1)[1].split("\n### ", 1)[0]  # noqa: E731
        documented_tools = re.findall(r"^- `([a-z_]+)`: ", section("Tools"), re.M)
        documented_resources = re.findall(r"^- `([a-z:/_-]+)`: ", section("Resources"), re.M)
        for server in (BACKEND / "mcp_server.py", BACKEND / "mcp-package" / "mcp_server.py"):
            with self.subTest(server=server.relative_to(ROOT)):
                self.assertEqual(documented_tools, [tool["name"] for tool in literal(server, "TOOLS")])
                self.assertEqual(documented_resources, [res["uri"] for res in literal(server, "RESOURCES")])

    def test_install_commands_match_the_package_entry_point(self):
        text = full_text()
        pyproject = (BACKEND / "mcp-package" / "pyproject.toml").read_text(encoding="utf-8")
        self.assertIn('gohirehumans-mcp = "mcp_server:main"', pyproject)
        for command in (
            f"uvx --from '{PACKAGE_SOURCE}' gohirehumans-mcp",
            f"claude mcp add gohirehumans -- uvx --from '{PACKAGE_SOURCE}' gohirehumans-mcp",
            f"codex mcp add gohirehumans -- uvx --from '{PACKAGE_SOURCE}' gohirehumans-mcp",
            f'"args": ["--from", "{PACKAGE_SOURCE}", "gohirehumans-mcp"]',
        ):
            self.assertIn(command, text)
        self.assertNotIn("npx", text)
        for variable in ("GOHIREHUMANS_API_KEY", "GOHIREHUMANS_AUTH_TOKEN", "GOHIREHUMANS_API_URL"):
            self.assertIn(f"`{variable}`", text)
            self.assertIn(variable, (BACKEND / "mcp-package" / "mcp_server.py").read_text(encoding="utf-8"))

    def test_truthful_limits_are_stated_and_no_unsupported_claims(self):
        text = full_text()
        for phrase in (
            "Workers receive the listed payout.",
            "Employers pay a 1% platform fee plus a fixed 3% processing charge where checkout is configured.",
            "Hourly job posts are not accepted right now.",
            "Workers must finish Stripe payout setup before applying to jobs.",
            "GoHireHumans does not vet, screen, or background-check workers.",
            "There is no outbound webhook or callback for task progress.",
            "accepts only a session token, never an API key",
            "Creating a job listing does not hire anyone or create or fund an order.",
        ):
            self.assertIn(phrase, text)
        allowed_negation = "GoHireHumans does not vet, screen, or background-check workers."
        self.assertEqual(claim_problems(text.replace(allowed_negation, "")), [])
        self.assertNotRegex(text, r"(?i)\bescrow\b|guarantee[ds]?\b|vetted|verified (workers|freelancers|humans)")
        self.assertNotRegex(text, r"ghh_[A-Za-z0-9]{8,}|Bearer [A-Za-z0-9]{16,}")

    def test_links_resolve_and_file_is_discoverable(self):
        text = full_text()
        for url in sorted(set(re.findall(r"https://www\.gohirehumans\.com/[^\s)`'\"]*", text))):
            with self.subTest(url=url):
                rel = urlsplit(url).path.lstrip("/")
                if not rel or rel.endswith("/"):
                    rel += "index.html"
                self.assertTrue((FRONTEND / rel).is_file(), rel)
        self.assertIn(SITE + "llms-full.txt", (FRONTEND / "llms.txt").read_text(encoding="utf-8"))
        urls = ET.parse(FRONTEND / "sitemap.xml").getroot().findall("{*}url")
        entry = [u for u in urls if u.findtext("{*}loc") == SITE + "llms-full.txt"]
        self.assertEqual(len(entry), 1)
        self.assertEqual(entry[0].findtext("{*}lastmod"), build_llms_full.REVIEWED)
        parser = robotparser.RobotFileParser()
        parser.parse((FRONTEND / "robots.txt").read_text(encoding="utf-8").splitlines())
        for agent in ("GPTBot", "OAI-SearchBot", "ClaudeBot", "PerplexityBot", "Google-Extended"):
            self.assertTrue(parser.can_fetch(agent, SITE + "llms-full.txt"), agent)


class LlmsFullGuardTests(unittest.TestCase):
    """The generator must refuse inputs that would publish a wrong or drifting reference."""

    def test_faq_drift_between_page_and_file_is_caught(self):
        drifted = full_text().replace("Review a small sample before agreeing the full scope.", "Review a sample.", 1)
        self.assertNotEqual(drifted, build_llms_full.render())

    def test_template_placeholder_left_unfilled_is_rejected(self):
        with self.assertRaises(ValueError):
            build_llms_full.render(template="# x\n{{FAQ}}\n{{UNKNOWN}}\n")

    def test_tool_list_drift_is_caught(self):
        dropped = full_text().replace("- `submit_review`: ", "- `submit_reviews`: ", 1)
        self.assertNotEqual(dropped, build_llms_full.render())
        tools = re.findall(r"^- `([a-z_]+)`: ", dropped.split("### Tools\n", 1)[1].split("\n### ", 1)[0], re.M)
        self.assertNotEqual(tools, [tool["name"] for tool in literal(BACKEND / "mcp_server.py", "TOOLS")])

    def test_tool_without_description_is_rejected(self):
        with self.assertRaises(ValueError):
            build_llms_full.tool_lines([{"name": "search_services", "description": ""}])


if __name__ == "__main__":
    unittest.main()
